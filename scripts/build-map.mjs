// Builds src/data/luzon-map.json: a projected SVG outline of central Luzon plus the
// positions of JTEC's job sites. Run with `npm run map` after editing src/data/places.json.
//
// Sources (both public domain): Natural Earth 1:10m admin-0 countries via `world-atlas`,
// and Natural Earth 1:10m lakes (scripts/data/ne_10m_lakes_luzon.json, pre-clipped).
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { geoMercator, geoPath } from 'd3-geo';
import { feature } from 'topojson-client';

const requireJson = createRequire(import.meta.url);
const root = new URL('../', import.meta.url);

const BOUNDS = { west: 119.7, east: 122.1, south: 13.9, north: 16.5 };
const WIDTH = 1000;

const world = requireJson('world-atlas/countries-10m.json');
const countries = feature(world, world.objects.countries);
const philippines = countries.features.find((f) => f.id === '608');
if (!philippines) throw new Error('Philippines (608) not found in world-atlas');

const lakes = JSON.parse(readFileSync(new URL('scripts/data/ne_10m_lakes_luzon.json', root)));
const { places, water } = JSON.parse(readFileSync(new URL('src/data/places.json', root)));

// Corner points rather than a polygon: d3-geo reads ring winding spherically, and a
// counter-clockwise box would mean "the whole globe except this box".
const frame = {
  type: 'MultiPoint',
  coordinates: [
    [BOUNDS.west, BOUNDS.south], [BOUNDS.east, BOUNDS.south],
    [BOUNDS.east, BOUNDS.north], [BOUNDS.west, BOUNDS.north],
  ],
};

// Size the canvas from the projected frame so nothing is stretched.
const probe = geoMercator().fitWidth(WIDTH, frame);
const [[x0, y0], [x1, y1]] = geoPath(probe).bounds(frame);
const HEIGHT = Math.round(((y1 - y0) / (x1 - x0)) * WIDTH);

const projection = geoMercator()
  .fitExtent([[0, 0], [WIDTH, HEIGHT]], frame)
  .clipExtent([[0, 0], [WIDTH, HEIGHT]]);
const path = geoPath(projection).digits(1);

const project = ({ lon, lat }) => projection([lon, lat]).map((v) => Math.round(v * 10) / 10);

const out = {
  _source: 'Natural Earth 1:10m (public domain). Generated by scripts/build-map.mjs.',
  width: WIDTH,
  height: HEIGHT,
  land: path(philippines),
  lakes: lakes.features.map((f) => ({ name: f.properties.name, d: path(f) })).filter((l) => l.d),
  places: Object.fromEntries(places.map((p) => [p.id, { label: p.label, xy: project(p) }])),
  water: water.map((w) => ({ id: w.id, label: w.label, xy: project(w) })),
};

writeFileSync(new URL('src/data/luzon-map.json', root), JSON.stringify(out));
console.log(`luzon-map.json ${WIDTH}x${HEIGHT}, land ${(out.land.length / 1024).toFixed(1)} KB, ${out.lakes.length} lakes, ${places.length} places`);
